import { useReveal, type RevealChain, type RevealState } from '../envelope/useReveal.js';
import tapUrl from '../../assets/Tap.svg';

/**
 * Кучка мини-превью — вход по умолчанию (второй, конверт, живёт в Envelope.tsx).
 *
 * Страница открывается маленькой заблюренной кучкой карточек: видно, что места
 * есть, и не видно, какие именно. Поверх — «Tap». По нажатию блюр уходит
 * дымкой, кучка сходится и вырастает до полного размера, дальше это обычная
 * колода-карусель.
 *
 * Такта два, и порядок у них тот же, что и был: сперва проясняется то, что
 * лежит перед глазами, и только потом оно едет. Идут они встык — рост трогается
 * в том же кадре, в котором блюр дошёл до нуля. Разбор — в шапке pile.css.
 *
 *   lead — через сколько после тапа трогается рост. Совпадает с --dur-fog в
 *          CSS, и это не совпадение чисел, а требование: рост обязан начаться
 *          там, где кончился блюр (см. pile.css).
 *   grow — сколько идёт рост, ровно как --dur-grow.
 *   tail — сколько ждём после роста, прежде чем считать кучку раскрытой.
 *          Нужен, чтобы `open` не пришёл в тот же кадр, в котором дорабатывает
 *          переход: на `open` со сцены снимаются сразу несколько правил.
 */
export const PILE_TIMING = { lead: 560, grow: 900, tail: 60 } as const;

/*
 * Цепочка не зависит ни от чего и живёт одним объектом на модуль: useReveal
 * держит её в зависимостях эффекта, и новая на каждый рендер перезаводила бы
 * таймер такта заново.
 *
 * Состояние `opening` кучка пропускает: клапана, которому надо откинуться, у
 * неё нет. Звука тоже нет — шуршать нечему, бумаги здесь никакой.
 *
 * Числа карточек в ней тоже нет. Раньше хвост растягивался разбегом по колоде,
 * но у кучки карман нулевой (--deal-tuck: 0px в pile.css), выезжать карточкам
 * неоткуда — разбег не двигал ничего и был чистым ожиданием, до четверти секунды.
 */
const PILE_CHAIN: RevealChain = {
  // Такт 1 — дымка: замутнение убывает, пелена над кучкой разрежается. К концу
  // такта от обеих не остаётся ничего — на этой же границе кучка и уходит из
  // разметки (InvitePage.tsx).
  unsealing: ['dealing', PILE_TIMING.lead],
  // Такт 2 — рост: разброс сходится, кучка дорастает до полного размера.
  dealing: ['open', PILE_TIMING.grow + PILE_TIMING.tail],
};

export function usePileReveal(autoOpen: boolean) {
  return useReveal(PILE_CHAIN, autoOpen);
}

interface PileProps {
  state: RevealState;
  onOpen(): void;
}

export function Pile({ state, onOpen }: PileProps) {
  const sealed = state === 'sealed';

  return (
    <>
      {/*
        Дымка и пелена — оба отдельными слоями над кучкой, а не фильтрами на ней
        самой. Пелене это нужно, чтобы разойтись шире краёв карточки, иначе у
        неё видно кромку ровно по её границе; замутнению — чтобы не отрезать
        стеклянную кромку карточки и не быть обязанным кончиться ровно на
        границе состояний. Полный разбор — в pile.css.
      */}
      <div className="pile__haze" aria-hidden="true" />
      <div className="pile__fog" aria-hidden="true" />

      {/*
        Мишень — вся площадь кучки, а не сам глиф: попасть пальцем в надпись в
        сорок пикселей на телефоне — задача не для гостя. Ровно та же причина,
        по которой у конверта кликабелен весь конверт, а не сургуч.
      */}
      <button type="button" className="pile__tap" onClick={onOpen} disabled={!sealed}>
        {/*
          «Tap» из макета — готовый глиф, выгруженный из Figma (assets/Tap.svg):
          жёлтый контур #FCED99 с прозрачными буквами и скруглением ровно как в
          дизайне. Картинкой, а не программным SVG: контур в макете нарисован
          вручную, повторять его обводкой и масками — лишний риск расхождений.
        */}
        <img className="pile__glyph" src={tapUrl} alt="" aria-hidden="true" />
        <span className="visually-hidden">Показать места</span>
      </button>
    </>
  );
}
