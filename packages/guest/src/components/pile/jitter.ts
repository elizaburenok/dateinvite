/**
 * Разброс карточек в кучке.
 *
 * Кучка обязана читаться кучкой, а не стопкой, сложенной по линейке, — значит
 * у каждой карточки свой сдвиг и свой наклон. Но «случайно» здесь нельзя:
 * Math.random() перевыдал бы разброс на каждом рендере, и кучка дёргалась бы
 * от любого постороннего обновления страницы.
 *
 * Поэтому разброс считается из id места — он у карточки не меняется, и кучка
 * держится на месте сама, без состояния и без useRef. Заодно у каждого
 * приглашения она своя: массив по индексу дал бы всем одну и ту же.
 */
export interface Jitter {
  /** Сдвиг вбок, доля амплитуды: [-1, 1]. */
  jx: number;
  /** Сдвиг по вертикали, доля амплитуды: [-1, 1]. */
  jy: number;
  /** Наклон, доля амплитуды: [-1, 1]. */
  rot: number;
}

export function jitter(seed: string, index: number): Jitter {
  return {
    jx: spread(fnv1a(`x${seed}`)),
    jy: spread(fnv1a(`y${seed}`)),
    /*
     * Сторона наклона чередуется через карточку, и только величина берётся из
     * id. Знак из хеша выпадает поровну, но на трёх-четырёх карточках он вполне
     * может выпасть одинаковым — и тогда вся кучка кренится в одну сторону и
     * читается веером, колодой карт в руке, а не брошенной кучей. Соседи,
     * наклонённые друг против друга, дают кучу при любом наборе id.
     */
    rot: Math.abs(spread(fnv1a(`r${seed}`))) * (index % 2 === 0 ? 1 : -1),
  };
}

/**
 * FNV-1a: короткая некриптографическая хеш-функция. Криптостойкость здесь ни к
 * чему, важно только одно — что близкие строки (demo-1, demo-2) расходятся по
 * всему диапазону, иначе соседние карточки получили бы почти одинаковый наклон
 * и разброса бы не вышло.
 */
function fnv1a(text: string): number {
  let hash = 0x811c9dc5;
  for (let index = 0; index < text.length; index += 1) {
    hash ^= text.charCodeAt(index);
    // imul, а не *: множитель большой, и обычное умножение вылезает за
    // точность double, теряя младшие биты — те самые, что и дают разброс.
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/**
 * Хеш в [-1, 1] с шагом в тысячную — мельче человеческого глаза.
 *
 * Величина при этом уводится от нуля: знак остаётся случайным, а размах идёт от
 * трети амплитуды и выше. Ровное распределение давало карточки, отклонившиеся
 * на градус, и такая выглядит не брошенной в кучу, а неаккуратно положенной в
 * стопку — одной хватает, чтобы вся кучка перестала читаться кучкой.
 */
function spread(hash: number): number {
  const raw = (hash % 2001) / 1000 - 1;
  return Math.sign(raw || 1) * (0.35 + Math.abs(raw) * 0.65);
}
