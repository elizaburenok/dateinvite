/**
 * Звук открытия конверта — синтез, а не файл. Бинарного ассета нет намеренно:
 * звук собирается прямо в Web Audio, поэтому его легко править числами, он
 * работает офлайн и не тянет за собой мегабайты.
 *
 * Слышно шорох рвущейся бумаги. Секрет в том, что бумага — это не ровный «свист»
 * шума и не единый удар, а россыпь мелких потрескиваний: множество коротких
 * резких щелчков подряд, гуще в начале (сам разрыв) и реже к концу (лист
 * оседает). Именно нерегулярная крошка щелчков читается ухом как бумага; ровный
 * тон или низкий толчок звучали бы «ударником», а не листом, поэтому ни того, ни
 * другого здесь нет. Весь звук отфильтрован по верхам — у бумаги нет низа, и
 * любой бас сразу превращает шорох в стук.
 *
 * Пускать звук можно только по жесту пользователя (клик по печати): без жеста
 * браузер блокирует автозапуск аудио. Поэтому единственная точка вызова —
 * коллбэк open() у запечатанного конверта; на авто-открытии (readOnly /
 * reduced-motion) он не срабатывает вовсе, и это ровно то, что нужно.
 *
 * AudioContext создаётся лениво, на первом клике, и переживает все следующие:
 * второй конверт на странице бывает разве что в деморежиме, но контекст всё
 * равно один на всех.
 */

let ctx: AudioContext | null = null;

function context(): AudioContext | null {
  if (typeof window === 'undefined') return null;
  const AC =
    window.AudioContext ?? (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
  if (!AC) return null;
  if (!ctx) ctx = new AC();
  // Контекст мог уснуть (вкладка была в фоне) — будим его тем же жестом.
  if (ctx.state === 'suspended') void ctx.resume();
  return ctx;
}

/** Сколько длится шорох. */
const DUR = 0.55;

/**
 * Пре-рендерим саму бумагу в буфер. Считаем сэмплы руками, а не гоняем ровный
 * шум через фильтр: щелчки должны быть неровными по времени и по громкости, а
 * такую крошку огибающей на живом узле не набрать.
 *
 * Складываем два слоя. Первый — тихий сплошной шум: это «шшш» скользящих друг о
 * друга волокон, фон под щелчками. Второй и главный — сами щелчки: короткие
 * затухающие всплески, разбросанные по времени неравномерно. В начале они идут
 * плотно (лист рвётся), к концу разрежаются (рваться уже нечему). Промежуток
 * между щелчками берём из экспоненты — так паузы выходят по-настоящему рваными,
 * а не одинаковыми.
 */
function crinkleBuffer(ac: AudioContext): AudioBuffer {
  const sr = ac.sampleRate;
  const len = Math.floor(sr * DUR);
  const buf = ac.createBuffer(1, len, sr);
  const d = buf.getChannelData(0);

  // Слой 1 — фоновое «шшш». Держим его тихим: чем тише фон, тем крупнее на нём
  // читаются щелчки — это и есть «хруст».
  for (let i = 0; i < len; i++) d[i] = (Math.random() * 2 - 1) * 0.08;

  // Слой 2 — щелчки. Идём по буферу прыжками от одного к другому.
  let i = 0;
  while (i < len) {
    const pos = i / len; // 0 в начале разрыва, 1 в конце
    // Средний зазор до следующего щелчка растёт к концу: плотно → редко.
    // Зазор чуть шире прежнего — щелчки не сливаются, а стоят крупными зёрнами.
    const meanGap = sr * (0.004 + pos * 0.03);
    i += Math.max(1, Math.floor(-Math.log(1 - Math.random()) * meanGap));
    if (i >= len) break;
    // Один щелчок: резкий всплеск шума, быстро гаснущий. Громче и длиннее
    // прежних — это делает хруст крупным; и меньше глохнет к концу, чтобы разрыв
    // не выдыхался слишком рано.
    const amp = (0.75 + Math.random() * 0.5) * (1 - pos * 0.35);
    const clen = Math.floor(sr * (0.003 + Math.random() * 0.011));
    for (let j = 0; j < clen && i + j < len; j++) {
      const k = i + j;
      const dec = 1 - j / clen;
      d[k] = (d[k] ?? 0) + (Math.random() * 2 - 1) * amp * dec * dec;
    }
    i += clen;
  }

  return buf;
}

export function playEnvelopeOpen(): void {
  // Настройку «меньше движения» уважаем и здесь: раз человек попросил тише
  // интерфейс, звук ему тоже незачем. На деле сюда с включённой настройкой и
  // не попасть (конверт открывается сразу, минуя клик), но полагаться на это
  // не будем.
  if (window.matchMedia?.('(prefers-reduced-motion: reduce)').matches) return;

  const ac = context();
  if (!ac) return;

  try {
    const t = ac.currentTime;

    // Общий выход держим тихо: звук — фон интерфейса, а не событие.
    const master = ac.createGain();
    master.gain.value = 0.44;
    master.connect(ac.destination);

    // Бумагу режем по низу: у листа нет баса, и любой бубнёж читается стуком, а
    // не шорохом. Верх слегка приглушаем, чтобы щелчки не резали слух.
    const hp = ac.createBiquadFilter();
    hp.type = 'highpass';
    // Ниже прежнего: пускаем в щелчки немного низа — от него хруст крупнее.
    // Выше этого начинается «стук», поэтому не опускаем дальше.
    hp.frequency.value = 1000;
    hp.Q.value = 0.7;
    const lp = ac.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.value = 8500;
    hp.connect(lp).connect(master);

    // Свежая крошка щелчков на каждый разрыв: два открытия подряд (демо) не
    // должны звучать одним и тем же семплом. Буфер дешёвый — считаем на месте.
    const paper = ac.createBufferSource();
    paper.buffer = crinkleBuffer(ac);

    // Общая огибающая поверх щелчков: мгновенный заход, мягкий спад к концу —
    // чтобы шорох не обрубался, а оседал.
    const env = ac.createGain();
    env.gain.setValueAtTime(0.0001, t);
    env.gain.exponentialRampToValueAtTime(1, t + 0.015);
    env.gain.setValueAtTime(1, t + 0.2);
    env.gain.exponentialRampToValueAtTime(0.0001, t + DUR);

    paper.connect(env).connect(hp);
    paper.start(t);
    paper.stop(t + DUR + 0.05);
  } catch {
    // Аудио — украшение: если контекст не завёлся, молча выходим.
  }
}
