import { useCallback, useEffect, useRef, useState } from 'react';
import type { GuestPlace } from '@invite/shared';
import { PlaceCard } from '../PlaceCard.js';
import { jitter } from '../pile/jitter.js';
import { usePrefersReducedMotion } from './usePrefersReducedMotion.js';
import type { EnvelopeState } from './Envelope.js';

interface CardCycleProps {
  places: GuestPlace[];
  selected: string | null;
  readOnly: boolean;
  state: EnvelopeState;
  onSelect(id: string): void;
}

/**
 * Сколько колода стоит на карточке, прежде чем сменить её.
 *
 * Паузу мерим не по движению, а по чтению: за это время нужно прочесть название
 * места и разглядеть, что это за место. Полсекунды на это не хватало — карточка
 * уходила ровно тогда, когда взгляд только доходил до неё.
 */
const HOLD_MS = 1600;
/** Сколько длится сама смена. */
const MOVE_MS = 980;
const STEP_MS = HOLD_MS + MOVE_MS;
/**
 * Смена идёт в два такта, и это главное, что отличает живую колоду от ровного
 * сдвига: сперва уходит верхняя карточка, и только освободившись от неё, стопка
 * одним коротким движением подтягивается вперёд. Пока такты шли вместе, всё
 * читалось одним переездом — не было видно, что стопка подаётся вслед за
 * ушедшей карточкой.
 *
 * Границу между тактами держит одно число: уход заканчивается ровно там, где
 * начинается подтяг. Это не совпадение, а условие — в этой точке ушедшая
 * карточка передаётся стопке (разбор в paint), и разрыв между тактами оставил бы
 * её на это время нигде.
 *
 * Уход длиннее подтяга, и это не поровну поделённая смена: путь у тактов разный.
 * Ушедшая карточка проходит весь свой рост, стопка — одну кромку, то есть раз в
 * двадцать меньше. Дать им одинаковое время значило бы гнать карточку через весь
 * экран с той же скоростью, с какой стопка переступает на кромку.
 */
const EXIT_MS = 560;
const PULL_MS = MOVE_MS - EXIT_MS;

/**
 * Пружина подачи выбранной карточки вперёд.
 *
 * Пружина, а не кривая с длительностью, потому что подача обязана стыковаться с
 * ходом колоды: нажимают в любой момент шага, и карточка в этот момент лежит где
 * угодно между своим слотом и верхом стопки. Кривая начинает движение заново, от
 * нуля до единицы за своё время, — и пока колода рядом доводила свой шаг сама,
 * движений выходило два подряд: карточка успевала вырасти, постоять пустой такт
 * и только потом доехать до места. Пружина же идёт из того положения, в каком
 * карточку застали, и приходит в подачу одним ходом.
 *
 * Затухание чуть ниже критического: перелёт около четырёх процентов читается
 * тем, что карточку подали в руку, а не выдвинули по направляющей. Больше брать
 * нельзя — на телефоне выросшая карточка и так почти во всю ширину экрана
 * (разбор при --cycle-focus в tokens.css), и перелёт ушёл бы за поля.
 *
 * Частота задаёт время хода: половина роста проходит за ~133ms, весь рост — за
 * ~300ms. Прежние числа (14.2) были заметно резче: там половина укладывалась в
 * сотню миллисекунд, и подача читалась щелчком, а не ходом.
 */
const PICK_FREQ = 11.5;
const PICK_DAMP = 0.75;

/**
 * Дуга подъёма: карточку не просто раздувают на месте, её вынимают из колоды —
 * значит в процессе она обязана приподняться и сесть обратно.
 *
 * Форма — импульс p²(1-p), нормированный так, чтобы пик равнялся единице (он
 * приходится на p = 2/3, где выражение даёт 4/27, отсюда и множитель). Годится
 * она тем, что зануляется на обоих концах хода: в начале — вместе с самой
 * подачей, в покое — точно в единице. Причём в начале зануляется дважды, вместе
 * с производной (за это отвечает квадрат), поэтому карточка трогается без
 * толчка вверх.
 *
 * Считать подъём от скорости пружины было бы физичнее, но пик тогда приходится
 * на ~100ms — карточка успевает подскочить раньше, чем заметно вырастет, и
 * подъём читается отдельным движением. Здесь пик стоит на 167ms, ровно посреди
 * роста, и оба движения читаются одним.
 *
 * За единицей выражение уходит в минус — и хорошо: на перелёте пружины карточка
 * оседает на пару пикселей ниже места и возвращается. Это её посадка.
 */
function pickLift(p: number): number {
  return 6.75 * p * p * (1 - p);
}
/**
 * Шаг интегрирования. Вчетверо мельче обычного кадра: кадры приходят неровно, а
 * на длинном кадре явный шаг у пружины расходится. На потолке dt в 64ms это
 * пятнадцать подшагов — для одной пружины ничто.
 */
const PICK_SUB_MS = 1000 / 240;

/**
 * На сколько пикселей курсор должен проехать, чтобы наведение считалось
 * намерением, а не позой (разбор при `armed`).
 *
 * Немного: задача порога — отсечь дрожь руки на мыши и шум тачпада, а не мерить
 * «достаточное» движение. Любой осознанный ход курсора к карточке перекрывает
 * шесть пикселей в первом же кадре.
 */
const ARM_DIST = 6;

/**
 * Стопка мест: компактная колода, которая сама перебирает карточки.
 *
 * Колода занимает высоту одной карточки плюс кромки соседей и целиком помещается
 * на экран — скролла здесь нет. Верхняя карточка лежит поверх всех и видна
 * целиком, остальные выглядывают из-под неё кромками снизу и с каждым шагом
 * вглубь становятся у́же. Идёт колода сама, пока конверт открыт и место не
 * выбрано; курсора она не ждёт, но наведению на переднюю карточку уступает —
 * разбор при `armed` и `paused`.
 *
 * Ход шаговый, а не сплошной: колода стоит HOLD_MS на каждой карточке — её
 * успевают прочитать, — и за MOVE_MS меняет верхнюю. На паузе карточек «в пути»
 * нет вовсе, поэтому клик всегда попадает туда, куда человек целился.
 *
 * Круг замыкается снизу, и это стоит объяснить, потому что на экране этого шва
 * не видно — так и задумано. Верхняя карточка уходит вверх и растворяется; к
 * концу этого такта её уже нет, и она встаёт в слот под самым дном стопки, где
 * её съедает растворённая задняя граница (маска в cycle.css). Дальше подтяг
 * поднимает всю стопку на кромку, и вместе со всеми она въезжает в последний
 * видимый слот — уже как новая карточка из глубины. Поэтому стопка и читается
 * бездонной: карточки приходят из-под неё, а не появляются на месте.
 *
 * Ширина колоды в потоке — одна карточка; полосу кромок под верхней карточкой
 * добирает CSS из --n, поэтому число мест ему нужно знать (мест бывает от трёх
 * до пяти).
 *
 * Всё состояние — одни часы `clock` в миллисекундах. Из них считаются оба такта
 * (`exitAt` и `pullAt`), а из них для каждой карточки — её глубина в колоде
 * `--d`: 0 наверху, 1, 2, … вглубь на кромку соседа, count — тот самый слот под
 * дном. Раскладку по `--d` — сдвиг, сужение, затемнение и растворение задней
 * границы — дальше делает CSS, и мерить рост карточки для этого не нужно: всё
 * выражается в кромках.
 *
 * Часы гоняем через requestAnimationFrame и пишем прямо в стили, минуя состояние
 * React: перерисовывать дерево на каждый кадр ради одного трансформа незачем.
 */
export function CardCycle({ places, selected, readOnly, state, onSelect }: CardCycleProps) {
  const count = places.length;
  const dealt = state === 'dealing' || state === 'open';
  const reducedMotion = usePrefersReducedMotion();

  // Курсор на передней карточке останавливает перебор: место читают, а не
  // листают мимо. Держим флагом, а не CSS-ом, потому что остановка — это
  // поведение колоды (часы замирают), а не вид карточки; сам подъём рисует уже
  // :hover в cycle.css. На тач-экранах наведения нет, и синтетический mouseenter
  // от тапа паузу бы не значил, поэтому включаем флаг только там, где ховер есть.
  const [hovered, setHovered] = useState(false);
  const canHover = useRef(false);
  useEffect(() => {
    canHover.current = typeof matchMedia === 'function' && matchMedia('(hover: hover)').matches;
  }, []);

  /**
   * Взвод паузы: наведение засчитывается, только если курсор приехал на карточку
   * сам, а не оказался на ней потому, что карточка появилась под ним.
   *
   * Без этого первая же встреча с колодой выглядела поломкой. Глиф «Tap» лежит
   * ровно на верхней карточке, и курсор после нажатия остаётся там же; как только
   * мишень уходит из разметки, карточка оказывается под неподвижным курсором —
   * Chrome в этот момент сам пересчитывает хит-тест и присылает mouseenter, без
   * единого движения мыши. Колода вставала, не сделав ни шага, и человек видел не
   * паузу, а мёртвый экран: паузу узнают по тому, что остановилось, а здесь ничего
   * и не двигалось.
   *
   * Починка — в том, чем пауза является по смыслу: это жест «хочу рассмотреть вот
   * эту», а жест есть действие, а не поза. Лежащий курсор действием не считается,
   * приехавший — считается.
   *
   * Считать движение с начала страницы нельзя: к самому глифу курсор как раз
   * подводят, и это движение взвело бы паузу ещё до нажатия. Поэтому взвод
   * сбрасывается всякий раз, когда колода трогается (эффект ниже) и когда
   * возвращаются на вкладку, — то есть ровно в тех точках, где карточка способна
   * подъехать под неподвижный курсор. Дальше нужно новое движение.
   */
  const [armed, setArmed] = useState(false);
  const armedRef = useRef(false);
  // Точка отсчёта. Берётся с первого же события после сброса, а не с места
  // нажатия: хит-тест под неподвижным курсором умеет присылать и pointermove,
  // и такое «движение» обязано стать началом отсчёта, а не самим движением.
  const armFrom = useRef<{ x: number; y: number } | null>(null);

  const disarm = useCallback(() => {
    armFrom.current = null;
    armedRef.current = false;
    setArmed(false);
  }, []);

  useEffect(() => {
    const onMove = (event: PointerEvent) => {
      if (armedRef.current) return;
      const from = armFrom.current;
      if (!from) {
        armFrom.current = { x: event.clientX, y: event.clientY };
        return;
      }
      const dx = event.clientX - from.x;
      const dy = event.clientY - from.y;
      // Порог — чтобы дрожь руки на мыши и шум тачпада не считались приездом.
      if (dx * dx + dy * dy < ARM_DIST * ARM_DIST) return;
      armedRef.current = true;
      setArmed(true);
    };

    window.addEventListener('pointermove', onMove, { passive: true });
    // Возврат на вкладку — тот же случай: состояние наведения есть, движения не
    // было. Ловим оба события, потому что порознь они дырявы: вкладку меняют без
    // потери фокуса окна, а окно теряет фокус без сокрытия вкладки.
    window.addEventListener('focus', disarm);
    document.addEventListener('visibilitychange', disarm);

    return () => {
      window.removeEventListener('pointermove', onMove);
      window.removeEventListener('focus', disarm);
      document.removeEventListener('visibilitychange', disarm);
    };
  }, [disarm]);

  // Пауза — это наведение, подтверждённое движением. Порознь ни то ни другое
  // колоду не останавливает.
  const paused = hovered && armed;

  const deckRef = useRef<HTMLDivElement>(null);
  // Часы колоды. Замкнуты по всему кругу (count * STEP_MS), чтобы не расти
  // бесконечно: за круг колода возвращается в то же положение.
  const clock = useRef(0);

  /**
   * Состояние подачи: прогресс пружины, её скорость, глубина выбранной карточки
   * в момент нажатия и она сама.
   *
   * Карточку держим ссылкой, а не ищем каждый раз по data-chosen: снятие выбора
   * убирает признак в тот же кадр, а пружине после этого ещё идти назад — и
   * вести ей будет некого.
   */
  const pick = useRef(0);
  const pickVel = useRef(0);
  const pickFrom = useRef(0);
  const pickEl = useRef<HTMLElement | null>(null);
  // Пружина встала — признаки подачи пора снимать, но не в этом кадре, а в
  // следующем. Зачем нужен лишний кадр, разобрано там, где флаг читают.
  const clearAt = useRef(false);
  // Первый кадр в подаче не участвует: карточка может быть выбрана уже к
  // загрузке, и разворачивать её тогда неоткуда и незачем.
  const first = useRef(true);

  // Выбранное место останавливает колоду: место читают, а не перебирают, и
  // уезжать из-под глаз карточка не должна. Соседей в этот момент не видно
  // (правила [data-focus] в cycle.css), так что перебирать всё равно нечего.
  const focused = selected !== null && places.some((place) => place.id === selected);
  const running = dealt && !reducedMotion && count > 1 && !focused;

  /*
   * Колода тронулась — взвод сбрасывается.
   *
   * Это и есть та точка, где карточка подъезжает под неподвижный курсор: раскрытие
   * кучки (курсор остался на «Tap») и возврат из крупного плана (курсор остался
   * там, где закрывали). В обоих случаях человек показать колоду в движении ещё не
   * успел, и останавливать её нечестно — сперва пусть увидит, что она ходит.
   */
  useEffect(() => {
    if (running) disarm();
  }, [running, disarm]);

  useEffect(() => {
    const deck = deckRef.current;
    if (!deck) return;

    const round = count * STEP_MS;
    // Насколько глубоко достаёт растворение задней границы — в кромках. Число
    // живёт в стилях (--cycle-haze), потому что это раскладка, а не поведение;
    // здесь оно нужно ровно затем, чтобы не вешать маску на карточки, до которых
    // растворение не дотягивается: маска обрезает тень, и платить ею за градиент,
    // который ничего не делает, незачем.
    const haze = parseFloat(getComputedStyle(deck).getPropertyValue('--cycle-haze')) || 0;

    const paint = () => {
      const step = Math.floor(clock.current / STEP_MS);
      const inMove = clock.current - step * STEP_MS - HOLD_MS;
      // Кого меняют на этом шаге: ту, что лежала наверху, когда шаг начался.
      // Границу берём по номеру шага, а не по чьей-то фазе: тактов два, и своя
      // граница у каждого разъехалась бы с чужой.
      const leaving = count > 1 && inMove > 0 ? step % count : -1;
      const out = clamp01(inMove / EXIT_MS);
      const pull = pullAt(inMove);
      const items = deck.querySelectorAll<HTMLElement>('.cycle__item');
      let front = 0;
      let nearest = Infinity;

      items.forEach((el, index) => {
        // Глубина в кромках: 0 — наверху, 1, 2, … — вглубь стопки.
        let d: number;
        if (index === leaving && out < 1) {
          // Уходит вверх и тает. В стопке её на это время нет вовсе: глубина
          // ноль, а весь ход держит --out и своё правило в cycle.css.
          d = 0;
          el.style.setProperty('--out', ease(out).toFixed(4));
          el.setAttribute('data-out', '');
          el.style.zIndex = '200';
        } else {
          el.removeAttribute('data-out');
          // Ушедшая возвращается из-под дна: её слот count подтяг поднимает в
          // count-1, ровно тем же движением, каким поднимает всех остальных.
          // Без mod: у всех остальных круг замыкает он, а этой карточке замыкать
          // нечего — она и так уже за последним слотом.
          d =
            index === leaving
              ? count - pull
              : count > 1
                ? (((index - step - pull) % count) + count) % count
                : 0;
          el.style.zIndex = String(Math.round(100 - d * 10));
          // Кликают верхнюю, а не ту, что в пути: целятся в место, а не в
          // карточку, которая уже уходит.
          if (d < nearest) {
            nearest = d;
            front = index;
          }
        }
        el.style.setProperty('--d', d.toFixed(4));
        // Задняя граница стопки растворена, и достаёт растворение только до
        // самых глубоких карточек — остальным маска не нужна. Стопке из одной
        // карточки не нужна вовсе: у неё нет задней границы, а низ этой
        // единственной карточки — её собственный край, а не дно стопки.
        if (count > 1 && d > count - 1 - haze) el.setAttribute('data-haze', '');
        else el.removeAttribute('data-haze');
      });

      items.forEach((el, index) => {
        if (index === front) el.setAttribute('data-front', '');
        else el.removeAttribute('data-front');
      });
    };

    /**
     * Поза подачи. Сам прогресс пишем на колоду — из него CSS считает рост,
     * наклон, прозрачность соседей и поле под выросшей карточкой, — а глубину
     * выбранной карточки на неё саму: из своего слота в колоде она выходит той
     * же пружиной, которой растёт. Оттого движение и одно: обе половины позы
     * ведёт одно число.
     */
    const paintPick = () => {
      deck.style.setProperty('--pick', pick.current.toFixed(4));
      deck.style.setProperty('--lift', pickLift(pick.current).toFixed(4));
      const el = pickEl.current;
      if (el) el.style.setProperty('--d', (pickFrom.current * (1 - pick.current)).toFixed(4));
    };

    /** Признаки подачи снимаем не по снятию выбора, а по остановке пружины. */
    const clearPick = () => {
      pickEl.current?.removeAttribute('data-pick');
      pickEl.current = null;
      deck.removeAttribute('data-focus');
    };

    const target = focused ? 1 : 0;

    if (focused) {
      const el = deck.querySelector<HTMLElement>('.cycle__item[data-chosen]');
      if (el) {
        if (pickEl.current && pickEl.current !== el) pickEl.current.removeAttribute('data-pick');
        // Слот, из которого карточку подают. Перечитывать его, пока пружина не
        // вернулась в ноль, нельзя: в --d тогда лежит поза подачи, а не глубина
        // в колоде. Колода всё это время стоит, так что слот и так прежний.
        if (pick.current === 0) {
          pickFrom.current = parseFloat(el.style.getPropertyValue('--d')) || 0;
        }
        pickEl.current = el;
        el.setAttribute('data-pick', '');
        deck.setAttribute('data-focus', '');
      }
    }

    // Без анимации и на первом кадре подача не разыгрывается, а просто есть:
    // движение либо попросили не показывать, либо показывать его ещё некому.
    if (first.current || reducedMotion) {
      pick.current = target;
      pickVel.current = 0;
    }
    first.current = false;

    paint();
    paintPick();
    // Эффект перезавёлся с уже отработавшей пружиной — снимать признаки можно
    // сразу: позу в этом случае никто не менял, разводить нечего.
    if (pick.current === 0 && !focused) {
      clearAt.current = false;
      clearPick();
    }

    // Шаг колоды больше не доводится до конца. Доводили его затем, чтобы колода
    // не вставала колом посреди смены, — но вставать ей теперь есть где: в
    // подаче соседей не видно вовсе, а выбранная карточка выходит из своего
    // слота пружиной, откуда бы её ни застали. Часы поэтому просто замирают, и
    // снятие выбора продолжает шаг ровно с того места, где его прервали.
    if (!running && pick.current === target) return;

    let raf = 0;
    let last = performance.now();

    const frame = (now: number) => {
      // Кадры не выдаются, когда вкладка в фоне: без потолка на dt колода после
      // возвращения прыгнула бы сразу на несколько карточек вперёд, а пружина —
      // сразу в конец хода.
      const dt = Math.min(now - last, 64);
      last = now;

      let alive = false;

      // Признаки подачи снимаем кадром позже, чем пружина встала, и это не
      // перестраховка.
      //
      // Защёлка приводит пружину в ноль из положения, до нуля не дошедшего (в
      // покое она подходит к цели асимптотически, разбор при springStep). Поза
      // на этом последнем шаге меняется — на тысячные доли процента, глазу
      // ничего, — но меняется. Сними признак в том же кадре, и браузер увидит
      // сразу два события: у карточки поехал трансформ и одновременно вернулся
      // transition, который на время подачи был снят. Он честно заводит переход
      // на все --dur-deal: двигать в нём нечего, а слой композиции он карточке
      // всё равно поднимает — и backdrop-filter стеклянной кромки на эти 640ms
      // размывает весь кадр вместо кольца (разбор в cycle.css). Читалось это
      // блюром, наплывавшим на карточку через секунду после возврата в колоду.
      //
      // Лишний кадр разводит события: сперва пружина дорисовывает конечную позу,
      // пока переход ещё снят, и только потом снимается признак — менять к тому
      // моменту нечего, и переходу не на чем завестись.
      if (clearAt.current) {
        clearAt.current = false;
        clearPick();
      }

      if (pick.current !== target || pickVel.current !== 0) {
        const next = springStep(pick.current, pickVel.current, target, dt);
        pick.current = next.p;
        pickVel.current = next.v;
        paintPick();
        if (pick.current === 0 && target === 0) clearAt.current = true;
        alive = true;
      }

      // Колода трогается, только когда карточка вернулась в свой слот. Иначе
      // подача и ход шли бы одновременно — те самые двое часов, от которых всё
      // это и уходит.
      if (running && pick.current === 0) {
        const phase = clock.current % STEP_MS;
        // Наведение останавливает перебор, но не колом посреди смены: если
        // курсор застал карточку в пути, шаг доводится до ближайшего покоя
        // (границы шага, откуда начинается пауза следующей карточки) и уже там
        // встаёт. В покое (фаза внутри HOLD) колода замирает сразу.
        if (paused && phase < HOLD_MS) {
          // стоим — часы не трогаем
        } else {
          const stepEnd = (Math.floor(clock.current / STEP_MS) + 1) * STEP_MS;
          const advance = paused ? Math.min(dt, stepEnd - clock.current) : dt;
          if (advance > 0) {
            clock.current = (clock.current + advance) % round;
            paint();
            alive = true;
          }
        }
      }

      if (alive) raf = requestAnimationFrame(frame);
    };

    raf = requestAnimationFrame(frame);
    return () => cancelAnimationFrame(raf);
  }, [running, focused, paused, reducedMotion, count]);

  return (
    <div
      className="cycle"
      ref={deckRef}
      data-dealt={dealt || undefined}
      // data-focus здесь больше нет намеренно: его ставит и снимает эффект.
      // React убрал бы признак в тот же кадр, в котором сняли выбор, — а подаче
      // после этого ещё идти назад, и она осталась бы без своих правил.
      // Не меньше одного: на пустом списке (--n - 1) ушло бы в минус и колода
      // получила бы отрицательный отступ. Такого конверта не бывает, но ломаться
      // на вырожденных данных компонент всё равно не должен.
      style={{ '--n': Math.max(1, count) } as React.CSSProperties}
    >
      {/* Распорка задаёт колоде высоту одной карточки: сами карточки лежат
          абсолютно и в потоке ничего не занимают. */}
      <div className="cycle__sizer" aria-hidden="true" />

      {places.map((place, index) => {
        // Разброс кучки. Считается из id и потому не меняется между рендерами —
        // paint() эти переменные не трогает вовсе, он пишет только --d и --out.
        const { jx, jy, rot } = jitter(place.id, index);

        return (
          <div
            key={place.id}
            className="cycle__item"
            data-chosen={selected === place.id || undefined}
            // Наведение на карточку останавливает перебор — если курсор до неё
            // доехал, а не лежал на ней с самого начала (разбор при `armed`).
            // События ловит только передняя: у остальных pointer-events сняты
            // (cycle.css), и mouseenter на них не приходит вовсе — курсор
            // проваливается к ней. Пока стоит пауза, колода не идёт, так что
            // передняя под курсором не сменится.
            onMouseEnter={canHover.current ? () => setHovered(true) : undefined}
            onMouseLeave={() => setHovered(false)}
            // Начальное значение — чтобы до первого кадра колода уже лежала стопкой,
            // а не сваливалась в кучу. Дальше --d каждый кадр переписывает paint().
            style={
              {
                '--d': index,
                '--i': index,
                '--jx': jx,
                '--jy': jy,
                '--rot': rot,
              } as React.CSSProperties
            }
          >
            {/*
              Слой разброса. Своим он нужен потому, что оба соседних заняты:
              внешний (.cycle__item) переписывается покадрово и вертится вокруг
              нижней кромки — поворот вокруг неё развернул бы кучку веером, как
              карты в руке; внутренний (.cycle__card) держит выезд из кармана и
              увеличение в фокусе, и разброс пришлось бы вклеивать в оба правила.
              Снаружи .cycle__card, а не внутри: затемнение глубины у неё на
              ::after, и оно обязано поворачиваться вместе с карточкой.
            */}
            <div className="cycle__jitter">
              <div className="cycle__card">
                <PlaceCard
                  place={place}
                  selected={selected === place.id}
                  readOnly={readOnly}
                  onSelect={onSelect}
                />
              </div>
            </div>
          </div>
        );
      })}
    </div>
  );
}

/**
 * Второй такт — подтяг стопки: 0 — она стоит там же, где стояла, 1 — поднялась
 * ровно на кромку и верхней стала следующая карточка.
 *
 * Трогается, только когда ушедшая карточка уже растаяла, и идёт по другой
 * кривой, чем она: с места быстро и потом долго тормозит. Стопка не переезжает
 * вслед за карточкой, а подаётся вперёд, освободившись от неё, — и читается это
 * ровно тем, что начало быстрее конца. Перелёта нет: карточки лежат друг на
 * друге, и трения между ними больше, чем пружины.
 *
 * Само начало при этом не в лоб. Чистого кубика хватало, пока такт был коротким:
 * рывок успевал слиться со сменой. На длинном такте он вылез отдельным движением,
 * и колода стала дёргаться — поэтому k заходит в кривую с разгона, вдвое сбавляя
 * скорость на старте. Характер такта это не меняет, только снимает толчок.
 */
function pullAt(inMove: number): number {
  const k = clamp01((inMove - EXIT_MS) / PULL_MS);
  const t = k * (0.5 + 0.5 * k);
  return 1 - (1 - t) ** 3;
}

/**
 * Кривая ухода верхней карточки: разгоняется и тормозится с нулевой скоростью на
 * концах, поэтому карточка трогается без рывка после паузы — в этой точке
 * скорость и так ноль, и стыка не видно.
 *
 * Ключевое здесь не концы, а середина. Раньше уход шёл кубической S-кривой, и
 * дело было не в длительности: у кубики середина вдвое быстрее средней скорости,
 * а карточка проходит весь свой рост — вот этот пик и читался скачком, сколько
 * такт ни удлиняй. Синус — самая пологая из S-кривых: у него пик всего в π/2
 * (≈1,57) раза выше средней, то есть карточка идёт почти равномерно и лишь
 * скругляет старт и финиш.
 *
 * Односторонние кривые сюда не годятся, и обе — по своей причине. Ease-out
 * трогается с полной скорости: ровно тот рывок в момент, когда карточка
 * отрывается от простоявшей полторы секунды стопки. Ease-in наоборот копит
 * скорость к концу — карточка сперва вяло приподнимается, а потом выстреливает,
 * и вместо одного скачка получается пауза и скачок.
 */
function ease(k: number): number {
  return 0.5 - Math.cos(Math.PI * k) / 2;
}

function clamp01(value: number): number {
  return Math.min(1, Math.max(0, value));
}

/**
 * Шаг пружины подачи — полуявный Эйлер с дроблением кадра.
 *
 * Дробление здесь не перестраховка: кадры приходят неровно, а на длинном кадре
 * явный шаг у пружины расходится — она не успокаивается, а раскачивается.
 *
 * Защёлка в конце — тоже не украшение. Пружина подходит к цели асимптотически и
 * сама в неё не приходит никогда; без защёлки колода не тронулась бы после
 * снятия выбора вовсе (она ждёт ровного нуля), а кадры заказывались бы вечно.
 *
 * Порог взят по видимости, а не по числу: прибавка роста — четырнадцать
 * процентов от 380px, то есть весь ход прогресса стоит 53px, и две тысячных от
 * него — это одна десятая пикселя. Двигаться мельче незачем. Скорость меряется
 * в долях прогресса за секунду, и 0.02 — это пиксель в секунду; она нужна
 * отдельно затем, что на перелёте пружина проходит цель насквозь, и по одному
 * положению защёлка сработала бы прямо посреди хода.
 */
function springStep(p: number, v: number, target: number, dtMs: number) {
  const k = PICK_FREQ * PICK_FREQ;
  const c = 2 * PICK_DAMP * PICK_FREQ;
  let rest = dtMs;

  while (rest > 0) {
    const h = Math.min(rest, PICK_SUB_MS) / 1000;
    rest -= PICK_SUB_MS;
    v += (-k * (p - target) - c * v) * h;
    p += v * h;
  }

  if (Math.abs(p - target) < 0.002 && Math.abs(v) < 0.02) return { p: target, v: 0 };
  return { p, v };
}
