import { useEffect, useRef } from 'react';
import type { GuestPlace } from '@invite/shared';
import { PlaceCard } from '../PlaceCard.js';
import { jitter } from '../pile/jitter.js';
import { usePrefersReducedMotion } from './usePrefersReducedMotion.js';
import type { EnvelopeState } from './Envelope.js';

interface CardCycleProps {
  places: GuestPlace[];
  selected: string | null;
  readOnly: boolean;
  state: EnvelopeState;
  onSelect(id: string): void;
}

/**
 * Сколько колода стоит на карточке, прежде чем сменить её.
 *
 * Паузу мерим не по движению, а по чтению: за это время нужно прочесть название
 * места и разглядеть, что это за место. Полсекунды на это не хватало — карточка
 * уходила ровно тогда, когда взгляд только доходил до неё.
 */
const HOLD_MS = 1600;
/** Сколько длится сама смена. */
const MOVE_MS = 980;
const STEP_MS = HOLD_MS + MOVE_MS;
/**
 * Смена идёт в два такта, и это главное, что отличает живую колоду от ровного
 * сдвига: сперва уходит верхняя карточка, и только освободившись от неё, стопка
 * одним коротким движением подтягивается вперёд. Пока такты шли вместе, всё
 * читалось одним переездом — не было видно, что стопка подаётся вслед за
 * ушедшей карточкой.
 *
 * Границу между тактами держит одно число: уход заканчивается ровно там, где
 * начинается подтяг. Это не совпадение, а условие — в этой точке ушедшая
 * карточка передаётся стопке (разбор в paint), и разрыв между тактами оставил бы
 * её на это время нигде.
 *
 * Уход длиннее подтяга, и это не поровну поделённая смена: путь у тактов разный.
 * Ушедшая карточка проходит весь свой рост, стопка — одну кромку, то есть раз в
 * двадцать меньше. Дать им одинаковое время значило бы гнать карточку через весь
 * экран с той же скоростью, с какой стопка переступает на кромку.
 */
const EXIT_MS = 560;
const PULL_MS = MOVE_MS - EXIT_MS;

/**
 * Стопка мест: компактная колода, которая сама перебирает карточки.
 *
 * Колода занимает высоту одной карточки плюс кромки соседей и целиком помещается
 * на экран — скролла здесь нет. Верхняя карточка лежит поверх всех и видна
 * целиком, остальные выглядывают из-под неё кромками снизу и с каждым шагом
 * вглубь становятся у́же. Ховера здесь нет намеренно — колода не ждёт курсора,
 * а идёт всегда, пока конверт открыт и место не выбрано.
 *
 * Ход шаговый, а не сплошной: колода стоит HOLD_MS на каждой карточке — её
 * успевают прочитать, — и за MOVE_MS меняет верхнюю. На паузе карточек «в пути»
 * нет вовсе, поэтому клик всегда попадает туда, куда человек целился.
 *
 * Круг замыкается снизу, и это стоит объяснить, потому что на экране этого шва
 * не видно — так и задумано. Верхняя карточка уходит вверх и растворяется; к
 * концу этого такта её уже нет, и она встаёт в слот под самым дном стопки, где
 * её съедает растворённая задняя граница (маска в cycle.css). Дальше подтяг
 * поднимает всю стопку на кромку, и вместе со всеми она въезжает в последний
 * видимый слот — уже как новая карточка из глубины. Поэтому стопка и читается
 * бездонной: карточки приходят из-под неё, а не появляются на месте.
 *
 * Ширина колоды в потоке — одна карточка; полосу кромок под верхней карточкой
 * добирает CSS из --n, поэтому число мест ему нужно знать (мест бывает от трёх
 * до пяти).
 *
 * Всё состояние — одни часы `clock` в миллисекундах. Из них считаются оба такта
 * (`exitAt` и `pullAt`), а из них для каждой карточки — её глубина в колоде
 * `--d`: 0 наверху, 1, 2, … вглубь на кромку соседа, count — тот самый слот под
 * дном. Раскладку по `--d` — сдвиг, сужение, затемнение и растворение задней
 * границы — дальше делает CSS, и мерить рост карточки для этого не нужно: всё
 * выражается в кромках.
 *
 * Часы гоняем через requestAnimationFrame и пишем прямо в стили, минуя состояние
 * React: перерисовывать дерево на каждый кадр ради одного трансформа незачем.
 */
export function CardCycle({ places, selected, readOnly, state, onSelect }: CardCycleProps) {
  const count = places.length;
  const dealt = state === 'dealing' || state === 'open';
  const reducedMotion = usePrefersReducedMotion();

  const deckRef = useRef<HTMLDivElement>(null);
  // Часы колоды. Замкнуты по всему кругу (count * STEP_MS), чтобы не расти
  // бесконечно: за круг колода возвращается в то же положение.
  const clock = useRef(0);

  // Выбранное место останавливает колоду: место читают, а не перебирают, и
  // уезжать из-под глаз карточка не должна. Соседей в этот момент не видно
  // (правила [data-focus] в cycle.css), так что перебирать всё равно нечего.
  const focused = selected !== null && places.some((place) => place.id === selected);
  const running = dealt && !reducedMotion && count > 1 && !focused;

  useEffect(() => {
    const deck = deckRef.current;
    if (!deck) return;

    const round = count * STEP_MS;
    // Насколько глубоко достаёт растворение задней границы — в кромках. Число
    // живёт в стилях (--cycle-haze), потому что это раскладка, а не поведение;
    // здесь оно нужно ровно затем, чтобы не вешать маску на карточки, до которых
    // растворение не дотягивается: маска обрезает тень, и платить ею за градиент,
    // который ничего не делает, незачем.
    const haze = parseFloat(getComputedStyle(deck).getPropertyValue('--cycle-haze')) || 0;

    const paint = () => {
      const step = Math.floor(clock.current / STEP_MS);
      const inMove = clock.current - step * STEP_MS - HOLD_MS;
      // Кого меняют на этом шаге: ту, что лежала наверху, когда шаг начался.
      // Границу берём по номеру шага, а не по чьей-то фазе: тактов два, и своя
      // граница у каждого разъехалась бы с чужой.
      const leaving = count > 1 && inMove > 0 ? step % count : -1;
      const out = clamp01(inMove / EXIT_MS);
      const pull = pullAt(inMove);
      const items = deck.querySelectorAll<HTMLElement>('.cycle__item');
      let front = 0;
      let nearest = Infinity;

      items.forEach((el, index) => {
        // Глубина в кромках: 0 — наверху, 1, 2, … — вглубь стопки.
        let d: number;
        if (index === leaving && out < 1) {
          // Уходит вверх и тает. В стопке её на это время нет вовсе: глубина
          // ноль, а весь ход держит --out и своё правило в cycle.css.
          d = 0;
          el.style.setProperty('--out', ease(out).toFixed(4));
          el.setAttribute('data-out', '');
          el.style.zIndex = '200';
        } else {
          el.removeAttribute('data-out');
          // Ушедшая возвращается из-под дна: её слот count подтяг поднимает в
          // count-1, ровно тем же движением, каким поднимает всех остальных.
          // Без mod: у всех остальных круг замыкает он, а этой карточке замыкать
          // нечего — она и так уже за последним слотом.
          d =
            index === leaving
              ? count - pull
              : count > 1
                ? (((index - step - pull) % count) + count) % count
                : 0;
          el.style.zIndex = String(Math.round(100 - d * 10));
          // Кликают верхнюю, а не ту, что в пути: целятся в место, а не в
          // карточку, которая уже уходит.
          if (d < nearest) {
            nearest = d;
            front = index;
          }
        }
        el.style.setProperty('--d', d.toFixed(4));
        // Задняя граница стопки растворена, и достаёт растворение только до
        // самых глубоких карточек — остальным маска не нужна. Стопке из одной
        // карточки не нужна вовсе: у неё нет задней границы, а низ этой
        // единственной карточки — её собственный край, а не дно стопки.
        if (count > 1 && d > count - 1 - haze) el.setAttribute('data-haze', '');
        else el.removeAttribute('data-haze');
      });

      items.forEach((el, index) => {
        if (index === front) el.setAttribute('data-front', '');
        else el.removeAttribute('data-front');
      });
    };

    paint();

    let raf = 0;

    if (running) {
      let last = performance.now();
      const run = (now: number) => {
        // Кадры не выдаются, когда вкладка в фоне: без потолка на dt колода
        // после возвращения прыгнула бы сразу на несколько карточек вперёд.
        clock.current = (clock.current + Math.min(now - last, 64)) % round;
        last = now;
        paint();
        raf = requestAnimationFrame(run);
      };
      raf = requestAnimationFrame(run);
      return () => cancelAnimationFrame(raf);
    }

    // Колода встала (выбрали место). На паузе она и так стоит ровно — вставать
    // никуда не надо.
    const step = Math.floor(clock.current / STEP_MS);
    const inStep = clock.current - step * STEP_MS;
    if (inStep <= HOLD_MS) {
      clock.current = step * STEP_MS;
      paint();
      return;
    }

    // Посреди смены колода не встаёт колом: шаг доводится до конца и уже там она
    // замирает. Доводка считается от абсолютного времени, а не покадрово: кадры
    // не выдаются, когда вкладка в фоне, и покадровая доводка там просто не дошла
    // бы до конца — вернувшись, человек застал бы карточку застывшей на полпути.
    // Здесь же первый кадр после возвращения увидит, что время вышло, и доложит
    // её на место.
    const from = clock.current;
    const to = (step + 1) * STEP_MS;
    const started = performance.now();
    const finish = (now: number) => {
      // Часы идут своим темпом, поэтому и замедление к концу шага то же самое,
      // что было бы на ходу: его держат ease и pullAt, а не эта доводка.
      const k = Math.min(1, (now - started) / (to - from));
      clock.current = k >= 1 ? to % round : from + (to - from) * k;
      paint();
      if (k < 1) raf = requestAnimationFrame(finish);
    };
    raf = requestAnimationFrame(finish);
    return () => cancelAnimationFrame(raf);
  }, [running, count]);

  return (
    <div
      className="cycle"
      ref={deckRef}
      data-dealt={dealt || undefined}
      // Место выбрано — колода в фокусе: соседей не видно, выбранная крупнее.
      data-focus={focused || undefined}
      // Не меньше одного: на пустом списке (--n - 1) ушло бы в минус и колода
      // получила бы отрицательный отступ. Такого конверта не бывает, но ломаться
      // на вырожденных данных компонент всё равно не должен.
      style={{ '--n': Math.max(1, count) } as React.CSSProperties}
    >
      {/* Распорка задаёт колоде высоту одной карточки: сами карточки лежат
          абсолютно и в потоке ничего не занимают. */}
      <div className="cycle__sizer" aria-hidden="true" />

      {places.map((place, index) => {
        // Разброс кучки. Считается из id и потому не меняется между рендерами —
        // paint() эти переменные не трогает вовсе, он пишет только --d и --out.
        const { jx, jy, rot } = jitter(place.id, index);

        return (
          <div
            key={place.id}
            className="cycle__item"
            data-chosen={selected === place.id || undefined}
            // Начальное значение — чтобы до первого кадра колода уже лежала стопкой,
            // а не сваливалась в кучу. Дальше --d каждый кадр переписывает paint().
            style={
              {
                '--d': index,
                '--i': index,
                '--jx': jx,
                '--jy': jy,
                '--rot': rot,
              } as React.CSSProperties
            }
          >
            {/*
              Слой разброса. Своим он нужен потому, что оба соседних заняты:
              внешний (.cycle__item) переписывается покадрово и вертится вокруг
              нижней кромки — поворот вокруг неё развернул бы кучку веером, как
              карты в руке; внутренний (.cycle__card) держит выезд из кармана и
              увеличение в фокусе, и разброс пришлось бы вклеивать в оба правила.
              Снаружи .cycle__card, а не внутри: затемнение глубины у неё на
              ::after, и оно обязано поворачиваться вместе с карточкой.
            */}
            <div className="cycle__jitter">
              <div className="cycle__card">
                <PlaceCard
                  place={place}
                  selected={selected === place.id}
                  readOnly={readOnly}
                  onSelect={onSelect}
                />
              </div>
            </div>
          </div>
        );
      })}
    </div>
  );
}

/**
 * Второй такт — подтяг стопки: 0 — она стоит там же, где стояла, 1 — поднялась
 * ровно на кромку и верхней стала следующая карточка.
 *
 * Трогается, только когда ушедшая карточка уже растаяла, и идёт по другой
 * кривой, чем она: с места быстро и потом долго тормозит. Стопка не переезжает
 * вслед за карточкой, а подаётся вперёд, освободившись от неё, — и читается это
 * ровно тем, что начало быстрее конца. Перелёта нет: карточки лежат друг на
 * друге, и трения между ними больше, чем пружины.
 *
 * Само начало при этом не в лоб. Чистого кубика хватало, пока такт был коротким:
 * рывок успевал слиться со сменой. На длинном такте он вылез отдельным движением,
 * и колода стала дёргаться — поэтому k заходит в кривую с разгона, вдвое сбавляя
 * скорость на старте. Характер такта это не меняет, только снимает толчок.
 */
function pullAt(inMove: number): number {
  const k = clamp01((inMove - EXIT_MS) / PULL_MS);
  const t = k * (0.5 + 0.5 * k);
  return 1 - (1 - t) ** 3;
}

/**
 * Кривая ухода верхней карточки: разгоняется и тормозится с нулевой скоростью на
 * концах, поэтому карточка трогается без рывка после паузы — в этой точке
 * скорость и так ноль, и стыка не видно.
 *
 * Ключевое здесь не концы, а середина. Раньше уход шёл кубической S-кривой, и
 * дело было не в длительности: у кубики середина вдвое быстрее средней скорости,
 * а карточка проходит весь свой рост — вот этот пик и читался скачком, сколько
 * такт ни удлиняй. Синус — самая пологая из S-кривых: у него пик всего в π/2
 * (≈1,57) раза выше средней, то есть карточка идёт почти равномерно и лишь
 * скругляет старт и финиш.
 *
 * Односторонние кривые сюда не годятся, и обе — по своей причине. Ease-out
 * трогается с полной скорости: ровно тот рывок в момент, когда карточка
 * отрывается от простоявшей полторы секунды стопки. Ease-in наоборот копит
 * скорость к концу — карточка сперва вяло приподнимается, а потом выстреливает,
 * и вместо одного скачка получается пауза и скачок.
 */
function ease(k: number): number {
  return 0.5 - Math.cos(Math.PI * k) / 2;
}

function clamp01(value: number): number {
  return Math.min(1, Math.max(0, value));
}
