/**
 * Фильтр стеклянной кромки карточки.
 *
 * Кромка карточки — стекло: подложка за ней размывается и вдобавок смещается,
 * и это смещение здесь главное. Матовое стекло даёт мутную полосу по краю,
 * линза — ту же фотографию, только уведённую вбок, как у среза настоящего стекла.
 *
 * Размытие с насыщенностью карточка берёт обычным backdrop-filter (invite.css),
 * а смещение живёт здесь, потому что CSS его задавать не умеет: backdrop-filter
 * умеет сослаться на фильтр по id, но описать — нет.
 *
 * Компонент ничего не показывает и на раскладку не влияет: svg спозиционирован
 * абсолютно и нулевого размера. Ставить его нужно один раз на страницу — id у
 * фильтра один, и второй такой же перебил бы первый.
 */

/**
 * Ширина стеклянной кромки, % ширины карточки. Живёт здесь, а не только в CSS,
 * потому что от неё зависят обе половины эффекта: и кольцо (--glass-w в
 * invite.css), и полосы этой карты. Разъехавшись, они дадут смещение мимо стекла.
 */
const RING = 0.9;

/** 480×314 из макета — та же пропорция, что у карточки (--card-ratio). */
const RATIO = 480 / 314;

/**
 * Карта смещения.
 *
 * Читается так: feDisplacementMap берёт из карты красный канал на смещение по
 * горизонтали и зелёный — по вертикали, а серединой шкалы (128) считает «не
 * двигать». Поэтому вся карта залита ровно серым, и только полосы по четырём
 * краям уходят от середины: у левой красный падает к нулю, у правой растёт к
 * максимуму, у верхней и нижней то же самое делает зелёный. В итоге подложка
 * стоит на месте везде, кроме кромки, — а на кромке её тянет поперёк края.
 *
 * Полосы одинаковые не в процентах, а в пикселях: карта растягивается на
 * карточку с её пропорцией, поэтому горизонтальные во столько же раз выше
 * вертикальных. Иначе на узких сторонах стекло вышло бы толще, чем на длинных.
 *
 * Углы — единственное упрощение: там полосы накладываются, и верхняя с нижней
 * перекрывают боковые, так что в углах остаётся смещение только по вертикали.
 * На кромке меньше процента это не читается, а честные углы потребовали бы
 * считать нормаль по расстоянию до скруглённого контура — это уже другая история.
 */
const MAP = `data:image/svg+xml,${encodeURIComponent(
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" preserveAspectRatio="none">
    <defs>
      <linearGradient id="l" x1="0" y1="0" x2="1" y2="0">
        <stop offset="0" stop-color="#008080"/><stop offset="1" stop-color="#808080"/>
      </linearGradient>
      <linearGradient id="r" x1="0" y1="0" x2="1" y2="0">
        <stop offset="0" stop-color="#808080"/><stop offset="1" stop-color="#ff8080"/>
      </linearGradient>
      <linearGradient id="t" x1="0" y1="0" x2="0" y2="1">
        <stop offset="0" stop-color="#800080"/><stop offset="1" stop-color="#808080"/>
      </linearGradient>
      <linearGradient id="b" x1="0" y1="0" x2="0" y2="1">
        <stop offset="0" stop-color="#808080"/><stop offset="1" stop-color="#80ff80"/>
      </linearGradient>
    </defs>
    <rect width="100" height="100" fill="#808080"/>
    <rect x="0" y="0" width="${RING}" height="100" fill="url(#l)"/>
    <rect x="${100 - RING}" y="0" width="${RING}" height="100" fill="url(#r)"/>
    <rect x="0" y="0" width="100" height="${RING * RATIO}" fill="url(#t)"/>
    <rect x="0" y="${100 - RING * RATIO}" width="100" height="${RING * RATIO}" fill="url(#b)"/>
  </svg>`,
)}`;

export function LensFilter() {
  return (
    <svg aria-hidden="true" width="0" height="0" style={{ position: 'absolute' }}>
      <filter
        id="glass-lens"
        x="0"
        y="0"
        width="100%"
        height="100%"
        colorInterpolationFilters="sRGB"
      >
        <feImage href={MAP} preserveAspectRatio="none" result="map" />
        {/* in="SourceGraphic" внутри backdrop-filter — это не сама карточка, а
            то, что лежит под ней: фильтру достаётся подложка.
            scale — на сколько пикселей кромка уводит её вбок. */}
        <feDisplacementMap
          in="SourceGraphic"
          in2="map"
          scale="18"
          xChannelSelector="R"
          yChannelSelector="G"
        />
      </filter>
    </svg>
  );
}
