-- Заметка к месту становится снимком в конверте, а не живым полем места (§3).
-- Раньше гость видел place.note (одна на все конверты с этим местом); теперь у
-- каждого конверта своя заметка к каждому месту, снятая в момент сборки.
ALTER TABLE envelope_places ADD COLUMN note TEXT;

-- Бэкфилл: уже отправленные конверты продолжают показывать ту заметку, что у их
-- мест сейчас. Без него старые конверты после смены источника чтения (см.
-- envelopePlaceRows) разом лишились бы заметок. NULL после этого означает ровно
-- «в этом конверте место без заметки», а не «данные не заполнены».
UPDATE envelope_places
SET note = (SELECT p.note FROM places p WHERE p.id = envelope_places.place_id)
WHERE note IS NULL;
