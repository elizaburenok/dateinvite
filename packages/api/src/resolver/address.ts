/**
 * Вытаскивает адрес из текста поста.
 *
 * Нужен потому, что OSM знает далеко не все заведения — особенно новые. Название
 * может не найтись вовсе, а вот улица с домом есть всегда. Тогда место сохраняется
 * с именем, которое человек написал сам, и координатами по адресу.
 */

/**
 * Типы улиц в именительном и в косвенных падежах: посты пишут не только
 * «Большой проспект, 46», но и «На Большом проспекте, 46». Склонённые формы
 * идут перед своими же основами («проспекте» до «проспект»), чтобы альтернация
 * ловила их целиком, а не откусывала основу и не спотыкалась об окончание.
 */
const STREET_WORDS =
  'ул\\.|улице|улица|ул|пер\\.|переулке|переулок|просп\\.|проспекте|проспект|пр-т|пр\\.|наб\\.|набережной|набережная|бульваре|бульвар|б-р|шоссе|ш\\.|площади|площадь|пл\\.|линии|линия|аллее|аллея|проезде|проезд';

/**
 * «наб. реки Карповки», «наб. канала Грибоедова» — половина петербургских адресов
 * пишется так. Между типом улицы и названием стоит строчное слово, и без него
 * шаблон «улица Название дом» рвался ровно на самом частом случае.
 */
const WATER_WORDS = 'реки|канала|ручья|протоки';

/**
 * Пометка района между улицей и домом: «Большой проспект П.С., 46/1»,
 * «Средний проспект В.О., 28». В Петербурге так уточняют одноимённые улицы на
 * Петроградской стороне и Васильевском острове, и без пропуска этой вставки
 * номер дома не приклеивался к улице — адрес терялся целиком.
 */
const DISTRICT_HINT = 'П\\.?\\s?С\\.?|В\\.?\\s?О\\.?';

/**
 * Дом: 3, 3/6, 5с1, 12к2, 7А. Буква корпуса приклеена к номеру без пробела:
 * иначе «46/1 в конце лета» затянуло бы в номер дома соседнее слово «в».
 */
const HOUSE = '\\d+[/\\-]?\\d*(?:[а-яА-Я]\\d*)?';

/**
 * Предлоги, с которых начинается фраза с адресом: «На Большом проспекте…»,
 * «В переулке…». Первое слово с заглавной — это предлог, а не имя улицы, и в
 * название его тащить нельзя, иначе геокодеру уезжает «На Большом проспект».
 */
const PREPOSITIONS = new Set([
  'на', 'в', 'во', 'по', 'у', 'за', 'к', 'ко', 'от', 'до', 'из', 'со', 'с', 'об', 'о', 'при',
  'над', 'под', 'про',
]);

/** Срезает ведущий предлог: «На Большом проспекте» → «Большом проспекте». */
function stripLeadingPreposition(value: string): string {
  const match = value.match(/^(\p{L}+)\s+(.+)$/u);
  if (match && PREPOSITIONS.has(match[1]!.toLowerCase())) return match[2]!;
  return value;
}

const PATTERNS: RegExp[] = [
  // «Провиантская ул., 3/6», «Лялин переулок, 5с1», «Большой проспект П.С., 46/1»
  new RegExp(
    `([\\p{Lu}][\\p{L}-]+(?:\\s+[\\p{Ll}\\p{L}-]+)?)\\s+(${STREET_WORDS})(?:\\s+(?:${DISTRICT_HINT}))?\\.?,?\\s*(${HOUSE})`,
    'u',
  ),
  // «улица Рубинштейна, 15», «проспект Мира 5», «наб. реки Карповки, 31»
  new RegExp(
    `(${STREET_WORDS})\\s+(?:(${WATER_WORDS})\\s+)?([\\p{Lu}][\\p{L}-]+(?:\\s+[\\p{L}-]+)?)(?:\\s+(?:${DISTRICT_HINT}))?\\.?,?\\s*(${HOUSE})`,
    'u',
  ),
];

export interface ExtractedAddress {
  /** Строка для геокодера: «Провиантская улица, 3». */
  query: string;
  /** Как было написано в посте — попадёт в карточку, если геокодер промолчит. */
  raw: string;
}

function normalizeStreetWord(word: string): string {
  const w = word.toLowerCase().replace(/\.$/, '');
  if (['ул', 'улица', 'улице'].includes(w)) return 'улица';
  if (['пер', 'переулок', 'переулке'].includes(w)) return 'переулок';
  if (['просп', 'проспект', 'проспекте', 'пр-т', 'пр'].includes(w)) return 'проспект';
  if (['наб', 'набережная', 'набережной'].includes(w)) return 'набережная';
  if (['б-р', 'бульвар', 'бульваре'].includes(w)) return 'бульвар';
  if (['ш', 'шоссе'].includes(w)) return 'шоссе';
  if (['пл', 'площадь', 'площади'].includes(w)) return 'площадь';
  if (['линия', 'линии'].includes(w)) return 'линия';
  if (['аллея', 'аллее'].includes(w)) return 'аллея';
  if (['проезд', 'проезде'].includes(w)) return 'проезд';
  return w;
}

/**
 * Улица без слова «улица»: «Малая Зеленина, 4», «Рубинштейна, 15».
 * Так пишут постоянно, и без этого шаблона адрес терялся целиком.
 *
 * Шаблон заведомо более жадный, поэтому ищем его только в начале поста —
 * там, где в постах про места и стоит адрес. В теле длинного текста
 * «Меню, 2» или «Зимой, 5» дали бы ложное срабатывание.
 *
 * Одной строки мало: в постах-анонсах первая строка — заголовок («Открытие!»),
 * а адрес приезжает следующим абзацем. Поэтому смотрим первые несколько
 * непустых строк, а не буквально первую.
 */
const BARE_STREET = new RegExp(
  `([\\p{Lu}][\\p{Ll}-]+(?:\\s+[\\p{Lu}][\\p{Ll}-]+){0,2}),\\s*(${HOUSE})(?![\\d.,]*\\s*(?:₽|руб|%))`,
  'u',
);

/** Слова, которые адресом быть не могут, даже если стоят перед числом. */
const NOT_A_STREET = new Set(['меню', 'зимой', 'летом', 'весной', 'осенью', 'цена', 'счёт', 'чек']);

/** Сколько непустых строк с начала поста считаем «шапкой» с адресом. */
const LEAD_LINES = 3;

/**
 * Строки идут по одной, а не склеенной простынёй: иначе «Малая Зеленина, 4»
 * с переносом строки за номером дома прихватывает первую букву следующей строки
 * («4\nв»), а склейка через запятую сама сочиняет адрес из двух соседних строк.
 */
function leadLines(text: string): string[] {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .slice(0, LEAD_LINES);
}

export function extractAddress(
  text: string | null | undefined,
  options: { exclude?: string[] } = {},
): ExtractedAddress | null {
  if (!text) return null;

  const exclude = new Set((options.exclude ?? []).map((value) => value.toLowerCase().trim()));

  // Первый шаблон — «Название улица дом», второй — «улица Название дом».
  const first = PATTERNS[0]!.exec(text);
  if (first) {
    const [raw, name, word, house] = first;
    // Номер дома вида 3/6 — это чаще всего угловой дом; геокодеру хватает первой части.
    const houseNumber = house!.split(/[/\-]/)[0]!.trim();
    // «На Большом проспекте» — предлог с заглавной прилипает к названию; срезаем
    // его и из адреса, и из строки для карточки.
    return {
      raw: stripLeadingPreposition(raw.trim()),
      query: `${stripLeadingPreposition(name!.trim())} ${normalizeStreetWord(word!)}, ${houseNumber}`,
    };
  }

  const second = PATTERNS[1]!.exec(text);
  if (second) {
    const [raw, word, water, name, house] = second;
    const houseNumber = house!.split(/[/\-]/)[0]!.trim();
    // «набережная реки Карповки» переставлять нельзя — порядок слов тут часть
    // названия, и «Карповки набережная» геокодер понимает уже хуже.
    const query = water
      ? `${normalizeStreetWord(word!)} ${water} ${name}, ${houseNumber}`
      : `${name} ${normalizeStreetWord(word!)}, ${houseNumber}`;
    return { raw: raw.trim(), query };
  }

  for (const line of leadLines(text)) {
    const bare = BARE_STREET.exec(line);
    if (!bare) continue;
    const [raw, name, house] = bare;
    const candidate = name!.trim();
    // Название места, стоящее перед номером, — не адрес: «Бергамот, 4».
    if (exclude.has(candidate.toLowerCase()) || NOT_A_STREET.has(candidate.toLowerCase())) continue;
    const houseNumber = house!.split(/[/\-]/)[0]!.trim();
    return { raw: raw.trim(), query: `${candidate}, ${houseNumber}` };
  }

  return null;
}
