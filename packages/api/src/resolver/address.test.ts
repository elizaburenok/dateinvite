import { describe, expect, it } from 'vitest';
import { extractAddress } from './address.js';

describe('извлечение адреса из текста поста', () => {
  it('«Провиантская ул., 3/6» — как в живом посте', () => {
    expect(extractAddress('нарядные завтраки в Баски & Монегаски, Провиантская ул., 3/6')).toEqual({
      raw: 'Провиантская ул., 3/6',
      // Дробь — угловой дом, геокодеру достаточно первой части.
      query: 'Провиантская улица, 3',
    });
  });

  it('обратный порядок: «улица Рубинштейна, 15»', () => {
    expect(extractAddress('бар на улица Рубинштейна, 15')?.query).toBe('Рубинштейна улица, 15');
  });

  it('корпус остаётся: «5с1» — это строение 1, геокодер его понимает', () => {
    expect(extractAddress('кофейня, Лялин переулок, 5с1')?.query).toBe('Лялин переулок, 5с1');
  });

  it('«наб. реки Карповки, 31, к.1» — как в живом посте', () => {
    // Строчное «реки» между типом улицы и названием рвало шаблон целиком,
    // а так пишется половина петербургских адресов.
    expect(
      extractAddress('Наш новый герой — gaby bistro, наб. реки Карповки, 31, к.1'),
    ).toEqual({
      raw: 'наб. реки Карповки, 31',
      // Порядок слов не переставляем: «Карповки набережная» геокодер понимает хуже.
      query: 'набережная реки Карповки, 31',
    });
  });

  it('канал тоже адрес: «наб. канала Грибоедова, 22»', () => {
    expect(extractAddress('бар на наб. канала Грибоедова, 22')?.query).toBe(
      'набережная канала Грибоедова, 22',
    );
  });

  it('сокращения раскрываются', () => {
    expect(extractAddress('Невский просп., 28')?.query).toBe('Невский проспект, 28');
    expect(extractAddress('Кутузовская наб., 12')?.query).toBe('Кутузовская набережная, 12');
  });

  it('без адреса возвращает null, а не выдумывает', () => {
    expect(extractAddress('очень вкусные завтраки, всем советую')).toBeNull();
    expect(extractAddress('')).toBeNull();
    expect(extractAddress(null)).toBeNull();
  });
});

describe('улица без слова «улица»', () => {
  it('«Малая Зеленина, 4» — как в живом посте', () => {
    expect(extractAddress('Ужин для особого случая — «Бергамот», Малая Зеленина, 4')).toEqual({
      raw: 'Малая Зеленина, 4',
      query: 'Малая Зеленина, 4',
    });
  });

  it('не принимает за адрес само название места', () => {
    expect(
      extractAddress('Ужин — «Бергамот», 4 стола', { exclude: ['Бергамот'] }),
    ).toBeNull();
  });

  it('жадный шаблон работает только в шапке поста', () => {
    // «Меню, 2» в теле текста адресом не является.
    expect(extractAddress('Ужин в «Бергамоте»\n\nМеню, 2 позиции на выбор')).toBeNull();
    // Глубоко в теле поста не смотрим вовсе: там «Тартар, 790» и прочий шум.
    expect(
      extractAddress('Открытие!\n\nЗашли на неделе\n\nБыло вкусно\n\nТартар, 790 — берите'),
    ).toBeNull();
  });

  it('адрес во втором абзаце после заголовка — находится', () => {
    // Первой строкой в постах-анонсах идёт «Открытие!», а адрес следующим абзацем.
    expect(extractAddress('Открытие!\n\nНаш новый герой — Малая Зеленина, 4')).toEqual({
      raw: 'Малая Зеленина, 4',
      query: 'Малая Зеленина, 4',
    });
  });

  it('перенос строки не попадает в номер дома', () => {
    // Строки разбираем по одной: иначе номер дома прихватывает первую букву
    // следующей строки — «4\nв», — и геокодер такого адреса не знает.
    expect(extractAddress('Пойдём в новое место\n\nМалая Зеленина, 4\n\nвкусно')).toEqual({
      raw: 'Малая Зеленина, 4',
      query: 'Малая Зеленина, 4',
    });
  });

  it('не склеивает адрес из двух соседних строк', () => {
    expect(extractAddress('Кофейня Март\n12 сортов кофе')).toBeNull();
  });

  it('не принимает цену за номер дома', () => {
    expect(extractAddress('Апельсиновые Дольки, 190₽')).toBeNull();
  });

  it('слово с типом улицы по-прежнему в приоритете', () => {
    expect(extractAddress('Кафе Март, Провиантская ул., 3/6')?.query).toBe('Провиантская улица, 3');
  });
});
